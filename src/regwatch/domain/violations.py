def normalize_violations(raw: str) -> list[str]:
    """把 ``violation_type`` 多值字段拆分并归一到分类体系。

    拆分后逐片段做「包含即归一」匹配：片段中包含某个体系内类型即归为该类型
    （例如「违规募集（向不合格投资者…）」归一为「违规募集」）；
    全部未命中时保留原片段，保证新类型不被丢弃。
    """
    result: list[str] = []
    for fragment in split_multi_value(raw):
        for known in VIOLATION_TYPES:
            if known in fragment:
                if known not in result:
                    result.append(known)
                break
        else:
            if fragment not in result:
                result.append(fragment)
    return result or ["未分类"]


def categorize_punishment(text: str) -> str:
    """把自由文本的处罚措施归入粗类别。"""
    for category, keywords in PUNISHMENT_CATEGORIES.items():
        if category == "其他":
            continue
        for keyword in keywords:
            if keyword in text:
                return category
    return "其他"


